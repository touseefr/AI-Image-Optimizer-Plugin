require_once AIIO_PLUGIN_DIR . 'includes/class-aiio-bulk-processor.php';

/**
 * Core plugin class. Wires everything together.
 */
final class AI_Image_Optimizer {

	private static $instance = null;

	public $settings;
	public $compressor;
	public $webp_converter;
	public $alt_text_generator;
	public $media_integration;
	public $bulk_processor;

	public static function instance() {
		if ( null === self::$instance ) {
			self::$instance = new self();
		}
		return self::$instance;
	}

	private function __construct() {
		$this->settings           = new AIIO_Settings();
		$this->compressor         = new AIIO_Compressor( $this->settings );
		$this->webp_converter     = new AIIO_Webp_Converter( $this->settings );
		$this->alt_text_generator = new AIIO_Alt_Text_Generator( $this->settings );
		$this->media_integration  = new AIIO_Media_Integration( $this->settings, $this->alt_text_generator );
		$this->bulk_processor     = new AIIO_Bulk_Processor( $this->settings, $this->compressor, $this->webp_converter, $this->alt_text_generator );

		add_action( 'plugins_loaded', array( $this, 'load_textdomain' ) );

		// Main pipeline: runs once a new attachment's metadata has been generated.
		add_filter( 'wp_generate_attachment_metadata', array( $this, 'process_new_upload' ), 20, 2 );

		// Serve .webp instead of original where supported, on the front end.
		add_filter( 'wp_content_img_tag', array( $this->webp_converter, 'maybe_swap_to_webp_in_html' ), 10, 3 );
	}

	public function load_textdomain() {
		load_plugin_textdomain( 'ai-image-optimizer', false, dirname( AIIO_PLUGIN_BASENAME ) . '/languages' );
	}

	/**
	 * Fired automatically for every new image upload.
	 *
	 * @param array $metadata      Attachment metadata generated by WP.
	 * @param int   $attachment_id Attachment ID.
	 * @return array Possibly modified metadata (unchanged here, but filter must return it).
	 */
	public function process_new_upload( $metadata, $attachment_id ) {

		if ( ! wp_attachment_is_image( $attachment_id ) ) {
			return $metadata;
		}

		// Avoid infinite loops / re-processing during regenerate-thumbnail style calls.
		if ( get_post_meta( $attachment_id, '_aiio_processed', true ) ) {
			return $metadata;
		}

		$file_path = get_attached_file( $attachment_id );

		if ( ! $file_path || ! file_exists( $file_path ) ) {
			return $metadata;
		}

		// 1. Compress the original + generated sizes.
		if ( $this->settings->get( 'enable_compression', true ) ) {
			$this->compressor->compress_attachment( $attachment_id, $metadata );
		}

		// 2. Generate WebP versions of the original + generated sizes.
		if ( $this->settings->get( 'enable_webp', true ) ) {
			$this->webp_converter->generate_webp_versions( $attachment_id, $metadata );
		}

		// 3. Generate AI alt text (only if the field is currently empty).
		if ( $this->settings->get( 'enable_alt_text', true ) ) {
			$this->alt_text_generator->maybe_generate_alt_text( $attachment_id );
		}

		update_post_meta( $attachment_id, '_aiio_processed', time() );

		return $metadata;
	}
}

/**
 * Kick things off.
 */
function aiio() {
	return AI_Image_Optimizer::instance();
}
add_action( 'plugins_loaded', 'aiio', 5 );

/**
 * Activation: sanity-check the uploads directory is writable.
 */
function aiio_activate() {
	$upload_dir = wp_upload_dir();
	if ( ! empty( $upload_dir['error'] ) ) {
		deactivate_plugins( AIIO_PLUGIN_BASENAME );
		wp_die( esc_html__( 'AI Image Optimizer could not activate: the WordPress uploads directory is not writable.', 'ai-image-optimizer' ) );
	}
	if ( ! get_option( 'aiio_settings' ) ) {
		add_option( 'aiio_settings', AIIO_Settings::defaults() );
	}
}
register_activation_hook( __FILE__, 'aiio_activate' );

/**
 * Deactivation: nothing destructive, just clear any scheduled events.
 */
function aiio_deactivate() {
	wp_clear_scheduled_hook( 'aiio_bulk_process_batch' );
}
register_deactivation_hook( __FILE__, 'aiio_deactivate' );
